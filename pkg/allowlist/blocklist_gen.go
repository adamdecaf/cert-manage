// Generates blocklist.go.
//
// In the history of x509 Certificates and CA's in the wild various accidnets
// and intentional misgivings have occurred.
//
// This blocklist is a collection of known CA's which are commonly removed in
// user applications (e.g. Chrome) and are never allowed in a store generated by
// cert-manage.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"os/user"
	"path"
	"runtime"
	"strings"
	"time"

	"github.com/adamdecaf/trustprune/pkg/certutil"
)

var (
	// Chrome maintains a .tar.gz file we can download of their blocklisted certificates and keys.
	chromeBlocklistTarball = "https://chromium.googlesource.com/chromium/src/+archive/main/net/data/ssl/blocklist.tar.gz"

	outputFilename = "pkg/allowlist/blocklist.go"
)

func main() {
	when := time.Now().Format("2006-01-02T03:04:05Z")
	who, err := user.Current()
	if err != nil {
		log.Fatalf("Unable to get user on %s", runtime.GOOS)
	}

	var buf bytes.Buffer

	fmt.Fprintf(&buf, `// Copyright 2018 Adam Shannon
//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.
// You may obtain a copy of the License at
//
//     http://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS,
// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
// See the License for the specific language governing permissions and
// limitations under the License.

// Fingerprints are derived from Chromium's net/data/ssl/blocklist data,
// Copyright The Chromium Authors, used under a BSD-style license. See NOTICE.
// Generated on %s by %s, any modifications will be overwritten
package allowlist
`, when, who.Username)

	// get certs from tarball
	certs, err := getChromeCerts(chromeBlocklistTarball)
	if err != nil {
		log.Fatalf("error getting chrome certs, err=%v", err)
	}

	// write certs to file
	fmt.Fprintf(&buf, "var blocklistedFingerprints = []string{\n")
	for i := range certs {
		fmt.Fprintf(&buf, "// %s\n", certs[i].desc)
		fmt.Fprintf(&buf, "`%s`,\n", certs[i].fingerprint)
	}
	fmt.Fprintf(&buf, "}\n")

	// format source code and write to blocklist.go
	out, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("error formatting output code, err=%v", err)
	}

	err = os.WriteFile(outputFilename, out, 0644)
	if err != nil {
		log.Fatalf("error writing file, err=%v", err)
	}
}

type cert struct {
	// SHA256 fingerprint
	fingerprint string
	// optional, some human level description
	desc string
}

func getChromeCerts(u string) ([]*cert, error) {
	req, err := http.NewRequest("GET", u, nil)
	if err != nil {
		return nil, fmt.Errorf("getChromeCerts: can't build request for %s: %w", u, err)
	}
	req.Close = true

	client := &http.Client{Timeout: 2 * time.Minute}
	resp, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	defer func() {
		if resp != nil && resp.Body != nil {
			if cerr := resp.Body.Close(); cerr != nil {
				log.Println(cerr)
			}
		}
	}()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("getChromeCerts: unexpected status %s for %s", resp.Status, u)
	}

	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, fmt.Errorf("getChromeCerts: reading body: %w", err)
	}

	var r io.Reader = bytes.NewReader(body)
	if len(body) >= 2 && body[0] == 0x1f && body[1] == 0x8b {
		r, err = gzip.NewReader(bytes.NewReader(body))
		if err != nil {
			return nil, fmt.Errorf("error reading gzip'd content, err=%w", err)
		}
	}

	// read files and accumulate certificates (as PEM blobs)
	var certs []*cert
	tfile := tar.NewReader(r)
	for {
		header, err := tfile.Next()
		if err != nil {
			if err == io.EOF {
				break // done with archive
			}
			return nil, fmt.Errorf("error reading tar header, err=%w", err)
		}

		if header.Size > 0 && header.Typeflag == tar.TypeReg { // regular file
			base := path.Base(header.Name)
			if !strings.HasSuffix(strings.ToLower(base), ".pem") {
				continue
			}
			bs, _ := io.ReadAll(tfile)
			cs, parseErr := certutil.ParsePEM(bs)
			for i := range cs {
				certs = append(certs, &cert{
					fingerprint: certutil.GetHexSHA256Fingerprint(*cs[i]),
					desc:        cs[i].Subject.String(),
				})
			}

			if len(cs) == 0 { // append whatever we can
				stem := strings.TrimSuffix(base, path.Ext(base))
				fp := stem
				if len(fp) > sha256.BlockSize {
					fp = fp[:sha256.BlockSize]
				}
				desc := base
				if parseErr != nil {
					desc = parseErr.Error()
				}
				certs = append(certs, &cert{
					fingerprint: fp,
					desc:        desc,
				})
			}
		}
	}

	if len(certs) == 0 {
		return nil, fmt.Errorf("getChromeCerts: no certificates found in %s", u)
	}

	return certs, nil
}
